def counts_entropy(values_or_counts, is_counts=False):
    """Order-0 empirical Shannon entropy (bits) + Miller-Madow correction.

    H_MM = H_naive + (K-1) / (2*N*ln2), K = number of distinct observed categories, N = sample
    size. Standard bias correction for plug-in entropy estimators (Miller 1955 / Madow 1948).
    Returns (H_naive_bits, H_mm_bits, K, n, reliable).
    """
    if is_counts:
        c = np.asarray(values_or_counts, dtype=np.float64)
        n = c.sum()
    else:
        v = np.asarray(values_or_counts)
        _, c = np.unique(v, return_counts=True)
        n = len(v)
    k = len(c)
    if n == 0 or k == 0:
        return 0.0, 0.0, 0, int(n), True
    p = c / n
    h = float(-(p * np.log2(p)).sum())
    h_mm = h + (k - 1) / (2.0 * n * LN2)
    reliable = k <= RELIABLE_MAX_DISTINCT
    return h, h_mm, int(k), int(n), bool(reliable)


def joint_entropy(a, b):
    """Joint empirical entropy (bits) of two equal-length integer arrays, + Miller-Madow.
    Uses a Counter over (a_i, b_i) pairs (exact, no hashing collisions, python ints)."""
    n = len(a)
    if n == 0:
        return 0.0, 0.0, 0, 0, True
    cnt = Counter(zip(a.tolist(), b.tolist()))
    c = np.array(list(cnt.values()), dtype=np.float64)
    k = len(c)
    p = c / n
    h = float(-(p * np.log2(p)).sum())
    h_mm = h + (k - 1) / (2.0 * n * LN2)
    reliable = k <= RELIABLE_MAX_DISTINCT
    return h, h_mm, int(k), int(n), bool(reliable)


def delta_entropy(values):
    """Entropy-of-deltas estimator: first difference (plain integer subtraction, no modular
    wraparound), order-0 entropy + Miller-Madow of the delta distribution. Used as the
    structure-sensitive estimator for ranges where the raw-value estimate is unreliable
    (distinct count too close to N for order-0 entropy of the raw values to mean anything,
    e.g. near-unique sequence/timestamp fields)."""
    if len(values) < 2:
        return 0.0, 0.0, 0, 0, True
    ivals = [int(x) for x in values.tolist()]
    d = [b - a for a, b in zip(ivals[:-1], ivals[1:])]
    return counts_entropy(np.array(d, dtype=object))


def data_chosen_partition(p_flip, k=2.0):
    """Partition chosen from the data alone: cut at bit b if the flip-probability gradient
    |p[b]-p[b-1]| exceeds mean+k*std of the gradient series (k=2.0, same multiplier as the
    shipped admission gate's gradient_gate, study_common.py gate_features -- used here only
    as a boundary-detection threshold, not as an admission decision or cost model). No encoder,
    no cost model: this rule only ever looks at the adjacent-row bit-flip profile.
    Returns a list of (lo, hi) half-open bit ranges covering [0, 64)."""
    p = np.asarray(p_flip, dtype=np.float64)
    g = np.zeros(64)
    g[1:] = np.abs(np.diff(p))
    thr = g[1:].mean() + k * g[1:].std()
    cuts = sorted(set([0, 64] + [b for b in range(1, 64) if g[b] > thr]))
    return [(cuts[i], cuts[i + 1]) for i in range(len(cuts) - 1)]
