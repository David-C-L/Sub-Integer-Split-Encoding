#!/usr/bin/env python3
"""Inline Sec. 7 tables of sample-sigconf.tex regenerated on the toplevel_sec7_20261014_1526 data, in the
tex's own layout (column order, decimals, bold = row/column best), as paste-ready tabular bodies + CSVs.

  tab:eval_composition  Addr. = SIS/realNested TopLevel (ladder/arm15), enc. = + OpenZL substreams (ladder/arm3),
                        raw = Arm A on the TopLevel split (ladder/armA), OpenZL = ladder/arm15 openzl/auto (all full
                        length, this run's build); Seq. (CSV only, dropped from the paper table 2026-10-17) = SIS/realNested --mlidc_sis_section_candidates=unrestricted
                        on the same binary (data/seq_toplevel/out/unrestricted_<col>.csv, seq_toplevel_20261017_2057;
                        bit-identical to the old ADDRESSABILITY_LADDER_SIZES_20261007.csv sis_unrestricted);
                        priced = Arm B, unchanged (ARM_B_OPENZL_AWARE_DP_20261007.csv armB_openzl_priced).
  tab:eval_crossformat  Nimble row: xf/nimble_raw auto_sis/auto bits (this run); BtrBlocks and FastLanes rows:
                        cross_format_clean_20260929_1705/xf/*_run1.csv (their own SIS ports, no Nimble SIS mode).
  tab:eval_planner_gap  plan_decode/summary.csv (this run): SIS (default) = SIS/realNested+view, re-priced =
                        SIS/hybrid+view, encoded = SIS/oracle_dp_selection+view.
  tab:eval_admission    admission/*.csv (this run), truth and metrics as make_table7_admission.py (gates.py);
                        rows as the tex's table7 (size estimate, bit-flip full profile, bit-flip 1,024 pairs).
"""
import csv, glob, os, sys
import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import artifact_paths as AP  # artifact-relative paths
ROOT = AP.ROOT
RUN = os.environ.get("SIS_TL_RUN", AP.TL)
OUT = os.environ.get("SIS_TABLE_OUT", AP.OUT)
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import paperstyle  # 2026-10-17: Sec. 7 short names
os.environ.setdefault("SIS_PROFILES_NPZ", f"{AP.DATA}/bitflip_profiles/profiles.npz")
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "admission"))
import gates  # noqa: E402

def bits(path, enc):
    for r in csv.DictReader(open(path)):
        if r["encoding"] == enc:
            assert r["validated"] == "1", (path, enc)
            return float(r["bits_per_elem"])
    raise KeyError((path, enc))

def fmt(v, best):
    s = f"{v:5.2f}"
    return f"\\textbf{{{s.strip()}}}" if round(v, 2) == round(best, 2) else s

# ---- composition ----
SEQ = os.environ.get("SIS_SEQ_RUN", f"{AP.DATA}/seq_toplevel/out")
LAD = pd.read_csv(f"{AP.DATA}/addressability_ladder_20261007/ADDRESSABILITY_LADDER_SIZES_20261007.csv")
ARMB = pd.read_csv(f"{AP.DATA}/addressability_ladder_20261007/ARM_B_OPENZL_AWARE_DP_20261007.csv")
COMP = [(c, paperstyle.short_label(c)) if c else None for c in
        ["snowflake", "xmark_prepost_full", "osm_h3_r9_fileorder", "osm_s2_l30_fileorder", "bing_quadkey", "uuidv7_hi",
         None, "publicbi_npi"]]
lines, rows = [], []
for item in COMP:
    if item is None:
        lines.append(r"\midrule"); continue
    c, name = item
    L = f"{RUN}/ladder"
    addr = bits(f"{L}/arm15_{c}.csv", "SIS/realNested")
    seq = bits(f"{SEQ}/unrestricted_{c}.csv", "SIS/realNested")  # 2026-10-17: same-build kUnrestricted rerun
    enc = bits(f"{L}/arm3_{c}.csv", "SIS/realNested")
    raw = bits(f"{L}/armA_{c}.csv", "SIS/pinned")
    pri = float(ARMB[(ARMB.column == c) & (ARMB.arm == "armB_openzl_priced")].bits_per_value.iloc[0])
    ozl = bits(f"{L}/arm15_{c}.csv", "openzl/auto")
    vals = [addr, enc, raw, pri, ozl]; b = min(vals)  # 2026-10-17: Seq. (+D/H) column dropped from the paper; kept in the CSV
    lines.append(f"{name:<12} & " + " & ".join(fmt(v, b) for v in vals) + r" \\")
    rows.append(dict(column=c, addr_toplevel=addr, seq_unrestricted=seq, enc=enc, raw=raw, priced=pri, openzl=ozl,
                     seq_vs_addr_pct=100 * (seq - addr) / addr))
open(f"{OUT}/tab_eval_composition_toplevel.tex", "w").write(
    "% tab:eval_composition body, TopLevel; generated by scripts/make_tables_toplevel.py\n" + "\n".join(lines) + "\n")
pd.DataFrame(rows).to_csv(f"{OUT}/tab_eval_composition_toplevel.csv", index=False)
cp = pd.DataFrame(rows)
print("composition: +Delta/Huff vs Addr: %.1f%% .. %.1f%%" % (cp.seq_vs_addr_pct.min(), cp.seq_vs_addr_pct.max()))

# ---- cross-format ----
XC = ["snowflake", "xmark_prepost_full", "osm_h3_r9_fileorder", "osm_s2_l30_fileorder", "bing_quadkey", "uuidv7_hi",
      "publicbi_npi", "publicbi_id1", "uuidv7_lo"]
XO = f"{AP.DATA}/cross_format_clean/xf"
xr = {}
nim = {}
for c in XC:
    a = bits(f"{RUN}/xf/nimble_raw/auto_{c}_r1_comp.csv", "Auto/view")
    s = bits(f"{RUN}/xf/nimble_raw/auto_sis_{c}_r1_comp.csv", "Auto/view")
    nim[c] = s / a
xr["Nimble"] = nim
for fmt_name, f in (("BtrBlocks", "btrblocks"), ("FastLanes", "fastlanes")):
    # median of bits over the three runs per arm, as make_cross_format_figure_panels.py:81 (BtrBlocks
    # selection varies between runs: H3 auto_sis/auto is 0.733/0.606/0.627 in run1/2/3)
    d = pd.concat([pd.read_csv(f"{XO}/{f}_run{r}.csv") for r in (1, 2, 3)]).groupby(
        ["dataset", "arm"]).bits_per_value.median()
    xr[fmt_name] = {c: d[(c, "auto_sis")] / d[(c, "auto")] for c in XC}
xl = [f"{k:<9} & " + " & ".join(f"{v[c]:.2f}" for c in XC) + r" \\" for k, v in xr.items()]
xh = " & " + " & ".join(paperstyle.short_label(c) for c in XC) + r" \\"
xhr = " & " + " & ".join(r"\rotatebox{90}{" + paperstyle.short_label(c) + "}" for c in XC) + r" \\"
open(f"{OUT}/tab_eval_crossformat_toplevel.tex", "w").write(
    "% tab:eval_crossformat body, Nimble row TopLevel; generated by scripts/make_tables_toplevel.py\n"
    "% header row with short names (replaces the paper's Snowfl./UUID-hi/UUID-lo header). Flat, it is 52.8 pt over\n"
    "% \\columnwidth (the current header is 27.1 pt over); rotated, it fits (both measured in a /tmp paper build):\n% " + xh + "\n"
    "% " + xhr + "\n"
    + "\n".join(xl) + "\n")
pd.DataFrame(xr).T.to_csv(f"{OUT}/tab_eval_crossformat_toplevel.csv")

# ---- planner gap ----
# SIS_PG_ROWS=10000000 builds the same body from the full-length rerun (data/planner_gap_10m/, its own
# summary.csv with plan_ms_median per arm) into tab_eval_planner_gap_10m.{tex,csv}.
PG_ROWS = int(os.environ.get("SIS_PG_ROWS", "524288"))
if PG_ROWS == 524288:
    S = pd.read_csv(f"{RUN}/plan_decode/summary.csv")
    PT = pd.read_csv(f"{AP.DATA}/plan_time/summary.csv", index_col=False)  # 2026-10-17: planning time (plan_time_20261017_2134)
    PG_SUFFIX = "toplevel"
else:
    S = pd.read_csv(f"{AP.DATA}/planner_gap_10m/summary.csv")
    PT = pd.DataFrame(dict(dataset=S.dataset, arm=S.arm.str.replace("+view", "", regex=False), rows=PG_ROWS,
                           row_frame="on", sample_size=np.where(S.arm.str.startswith("SIS/oracle"), PG_ROWS, 2048),
                           plan_ms_median=S.plan_ms_median))
    PG_SUFFIX = "10m"
PL = [("default", "SIS/realNested+view"), ("re-priced", "SIS/hybrid+view"), ("encoded", "SIS/oracle_dp_selection+view")]
pg = {}
for ds in ("snowflake", "osm_h3_r9_fileorder"):
    for lab, arm in PL:
        r = S[(S.dataset == ds) & (S.arm == arm)].iloc[0]
        assert str(r.validated_all) == "True", (ds, arm)
        t = PT[(PT.dataset == ds) & (PT.arm == arm.replace("+view", "")) & (PT.rows == PG_ROWS) & (PT.row_frame == "on")
               & (PT.sample_size == (PG_ROWS if lab == "encoded" else 2048))].iloc[0]  # encoded: priced over the whole column
        pg[(ds, lab)] = (float(r.bits_per_value), int(r.sections), float(r.point_ns_per_probe), float(t.plan_ms_median))
def cell(ds, lab, i, best):
    v = pg[(ds, lab)][i]
    s = (f"{v:.2f}" if i == 0 else f"{int(v)}" if i == 1 else f"{v:.1f}" if v < 10 else f"{v:,.0f}".replace(",", "{,}"))
    return f"\\textbf{{{s}}}" if i != 1 and v == best else s
pl = []
for lab, _ in PL:
    parts = []
    for ds in ("snowflake", "osm_h3_r9_fileorder"):
        bb = min(pg[(ds, l)][0] for l, _ in PL); bp = min(pg[(ds, l)][2] for l, _ in PL)
        bt = min(pg[(ds, l)][3] for l, _ in PL)
        parts += [cell(ds, lab, 0, bb), cell(ds, lab, 1, None), cell(ds, lab, 3, bt), cell(ds, lab, 2, bp)]
    pl.append(f"{lab:<16} & " + " & ".join(parts) + r" \\")
open(f"{OUT}/tab_eval_planner_gap_{PG_SUFFIX}.tex", "w").write(
    f"% tab:eval_planner_gap body, TopLevel, {PG_ROWS:,} rows; generated by scripts/make_tables_toplevel.py\n" + "\n".join(pl) + "\n")
pd.DataFrame([dict(dataset=k[0], planner=k[1], bits=v[0], sections=v[1], point_ns=v[2], plan_ms=v[3]) for k, v in pg.items()]).to_csv(
    f"{OUT}/tab_eval_planner_gap_{PG_SUFFIX}.csv", index=False)
for ds in ("snowflake", "osm_h3_r9_fileorder"):
    d, rp, ex = (pg[(ds, l)] for l, _ in PL)
    print(f"planner gap {ds}: default/exact size +{100 * (d[0] / ex[0] - 1):.1f}%; point re-priced {rp[2] / d[2]:.2f}x, exact {ex[2] / d[2]:.2f}x")

# ---- admission (tex layout) ----
A = f"{RUN}/admission"
fs = sorted(glob.glob(f"{A}/*.csv"))
d = pd.concat([pd.read_csv(f).assign(col=os.path.basename(f)[:-4]) for f in fs], ignore_index=True)
enc = d[(d.row_kind == "encoder") & (d.skipped != 1)]
truth = {}
for c, g in enc.groupby("col"):
    b = g.set_index("encoding").payload_bytes
    sis = min(b[a] for a in gates.SIS_ARMS if a in b)
    other = min(v for a, v in b.items() if not a.startswith("SIS/") and not a.startswith("openzl"))
    truth[c] = bool(sis < 0.99 * other)
N = sorted(truth)
h = d[d.row_kind == "heuristic"].set_index("col")
adm = d[d.row_kind == "admission"]
def gate(pairs):
    g = adm[(adm.admission_mode == "bitflip") & (adm.profile_pairs == pairs)].set_index("col")
    return {n: int(g.loc[n, "decision"]) == 1 for n in N}, g.decision_ns.median() / 1e3
RW = [("Size estimate", {n: int(h.loc[n, "estimate_admits"]) == 1 for n in N}, h.decision_ns.median() / 1e3)]
gf, uf = gate(0); g1, u1 = gate(1024)
RW += [("Bit-flip, full profile", gf, uf), ("Bit-flip, 1{,}024 pairs", g1, u1)]
tl = [f"% generated by scripts/plot/make_tables_toplevel.py",
      f"% data: data/toplevel_sec7/admission ({len(N)} columns, {sum(truth.values())} positive)",
      r"\begin{tabular}{@{}lrrrrrr@{}}", r"\toprule", r"Admission & FP & FN & Precision & Recall & F1 & $\mu$s \\", r"\midrule"]
ac = []
for lab, pred, us in RW:
    tp, fp, fn, tn, P, R, F1 = gates.metrics(pred, truth, N)
    t = f"{us:,.0f}".replace(",", "{,}")
    tl.append(f"{lab:<24} & {fp} & {fn} & {P:.3f} & {R:.3f} & {F1:.3f} & {t} \\\\")
    ac.append(dict(row=lab.replace("{,}", ","), TP=tp, FP=fp, FN=fn, TN=tn, P=P, R=R, F1=F1, median_us=us,
                   FP_columns=";".join(n for n in N if pred[n] and not truth[n]),
                   FN_columns=";".join(n for n in N if not pred[n] and truth[n])))
tl += [r"\bottomrule", r"\end{tabular}"]
open(f"{OUT}/table7_admission_confusion.tex", "w").write("\n".join(tl) + "\n")
pd.DataFrame(ac).to_csv(f"{OUT}/table7_admission_confusion.csv", index=False)
sisenc = enc[enc.encoding == "SIS/realNested"].set_index("col").encode_ns
g = adm[(adm.admission_mode == "bitflip") & (adm.profile_pairs == 1024)].set_index("col")
share = (g.decision_ns / sisenc).dropna() * 100
print(f"admission: {len(N)} columns, {sum(truth.values())} positive; gate 1024 cost {share.min():.3f}%..{share.max():.3f}% of SIS encode (median {share.median():.3f}%)")
for r in ac:
    print("  ", r["row"], "FP", r["FP"], r["FP_columns"], "FN", r["FN"], r["FN_columns"], "us %.1f" % r["median_us"])

# ---- 2026-10-17: complete tabulars (header + body) for the overfull-table fixes ----
# Each replaces the paper's whole \begin{tabular}...\end{tabular} (font size / \tabcolsep stay in the table env).
ch = [r"\begin{tabular}{lrrrrr}", r"\toprule",
      r" & & \multicolumn{3}{c}{Compressed sections} & \multicolumn{1}{c}{Column} \\",
      r"\cmidrule(lr){3-5}\cmidrule(lr){6-6}",
      r"Column & \SIS{} & enc. & raw & priced & OpenZL \\", r"\midrule"]
open(f"{OUT}/tab_eval_composition_full.tex", "w").write(
    "% tab:eval_composition, complete tabular (header + TopLevel body); generated by scripts/make_tables_toplevel.py\n"
    + "\n".join(ch + lines + [r"\bottomrule", r"\end{tabular}"]) + "\n")
xf = [r"\begin{tabular}{l*{6}{r}@{\hspace{6pt}}*{3}{r}}", r"\toprule", xhr.lstrip(), r"\midrule"] + xl + [r"\bottomrule", r"\end{tabular}"]
open(f"{OUT}/tab_eval_crossformat_full.tex", "w").write(
    "% tab:eval_crossformat, complete tabular, rotated short-name header; generated by scripts/make_tables_toplevel.py\n"
    + "\n".join(xf) + "\n")
